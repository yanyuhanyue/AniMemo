// Run against a synthetic review instance. Uses real API and isolated accounts.
import { chromium } from '../.local/tools/browser/node_modules/playwright/index.mjs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
const access = JSON.parse(await readFile(process.env.REVIEW_ADMIN_ACCESS || '.local/output/theme-review-access.json', 'utf8'));
const packagePath = process.env.REVIEW_THEME_PACKAGE || '.local/output/notes-gallery.animemo-plugin';
const origin = process.env.REVIEW_ORIGIN || access.origin;
const output = process.env.REVIEW_OUTPUT || '.local/output/browser/theme-templates';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.ANIMEMO_BROWSER || '/usr/bin/chromium', args: ['--no-sandbox'] });
const admin = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
for (const p of [admin, page]) p.setDefaultTimeout(15000);
const report = { checks: [], axe: [], errors: [] };
for (const p of [admin, page]) p.on('pageerror', e => report.errors.push(e.message));
const call = async (p, method, path, data) => { const r = await p.request.fetch(origin + path, { method, headers: { Origin: origin }, data }); assert.ok(r.ok(), `${method} ${path}: ${r.status()} ${(await r.text()).slice(0, 150)}`); return r.status() === 204 ? null : r.json(); };
const click = async locator => { await page.locator('body').ariaSnapshot(); await locator.click(); };
const mark = text => { report.checks.push(text); console.log(text); };
const scan = async name => {
  await page.evaluate(await readFile('.local/tools/browser/node_modules/axe-core/axe.min.js', 'utf8'));
  const violations = await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })));
  report.axe.push({ name, violations }); assert.deepEqual(violations, []);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'page fits');
  for (const e of await page.locator('.theme-frame,.exhibit,.dialog').all()) assert.ok(await e.evaluate(n => n.scrollWidth <= n.clientWidth + 1), 'surface fits');
};
const open = () => click(page.getByRole('button', { name: '札记外观', exact: true }));
const inventory = () => call(admin, 'GET', '/api/v1/admin/plugins');
const change = async (item, action) => call(admin, 'POST', `/api/v1/admin/plugins/${item.manifest.slug}`, { action, version: item.manifest.version, revision: item.revision });
let original, forkSlug;
try {
  await call(admin, 'POST', '/api/v1/auth/login', { email: access.email, password: access.password });
  original = (await inventory()).items.find(p => p.manifest.slug === 'notes-gallery' && p.active);
  await admin.goto(origin + '/admin#plugins');
  await admin.getByRole('navigation', { name: '管理导航' }).getByRole('button', { name: '插件', exact: true }).click();
  const packaged = JSON.parse(await readFile(packagePath, 'utf8'));
  await admin.getByLabel('选择插件包').setInputFiles(packagePath);
  await admin.getByRole('button', { name: '已审核，安装此版本', exact: true }).click();
  await admin.getByRole('dialog').waitFor({ state: 'detached' });
  await change((await inventory()).items.find(p => p.manifest.slug === packaged.manifest.slug && p.manifest.version === packaged.manifest.version), 'activate');
  await call(page, 'POST', '/api/v1/auth/register', { email: `templates-${randomUUID()}@example.test`, password: `test-${randomUUID()}`, display_name: '主题模板合成验收' });
  const entry = await call(page, 'POST', '/api/v1/entries', { title: '给夏天的来信 · 合成验收' });
  const png = await readFile('server/examples/notes-gallery/assets/notebook.png');
  assert.ok((await page.request.put(`${origin}/api/v1/entries/${entry.id}/cover?version=${entry.version}`, { headers: { Origin: origin, 'Content-Type': 'image/png' }, data: png })).ok());
  const first = await call(page, 'POST', '/api/v1/memory/notes', { anime_id: entry.anime_id, title: '散场以后，还想再读一遍', body: '并不是每一段回忆都有准确的日期。\n\n有时，只是想记住故事留在心里的温度。', tags: ['夏天', '温柔的故事'], highlight: true });
  await call(page, 'POST', '/api/v1/memory/notes', { title: '在某个遥远的午后', body: '翻到这一页的时候，又想起了那时的自己。', occurred_on: '2024', time_precision: 'year' });
  const media = await call(page, 'POST', '/api/v1/memory/media', { byte_size: png.length });
  assert.ok((await page.request.put(`${origin}/api/v1/memory/media/${media.id}`, { headers: { Origin: origin, 'Content-Type': 'image/png' }, data: png })).ok());
  const spoiler = await call(page, 'POST', '/api/v1/memory/notes', { title: '最后一幕的秘密', body: '主题不能提前显示这段剧透正文。', spoiler: true, media_ids: [media.id] });
  const mediaRequests = [];
  page.on('request', request => { if (request.method() === 'GET' && request.url().includes('/memory/media/' + media.id)) mediaRequests.push(request.url()); });
  await page.goto(origin + '/memory#notes'); await page.locator('.note-sheet-entry').first().waitFor();
  await open(); await click(page.getByRole('button', { name: /星笺展架/ }));
  await page.getByRole('heading', { name: '故事散场，回忆上架。' }).waitFor();
  assert.equal((await call(page, 'GET', '/api/v1/themes')).selected_slug, '');
  assert.equal(await page.locator('.note-sheet-entry').count(), 3, 'preview does not change the live list');
  await scan('template preview'); await page.screenshot({ path: output + '/preview.png' });
  await click(page.getByRole('button', { name: '取消', exact: true }));
  await open(); await click(page.getByRole('button', { name: /星笺展架/ })); await click(page.getByRole('button', { name: '应用外观', exact: true }));
  await page.getByRole('dialog').waitFor({ state: 'detached' }); await page.locator('.shelf .exhibit').first().waitFor();
  assert.equal(await page.locator('.shelf .exhibit').count(), 3);
  assert.equal(await page.getByText(spoiler.body, { exact: true }).count(), 0);
  assert.equal(mediaRequests.length, 0, 'spoiler images never fetched before disclosure');
  const options = await call(page, 'GET', '/api/v1/themes');
  const chosen = options.items.find(i => i.manifest.slug === options.selected_slug);
  await page.waitForFunction(f => [...document.fonts].some(face => face.family === f && face.status === "loaded"), `am-theme-${chosen.digest.slice(0, 16)}-${chosen.manifest.notes_theme.presentation.assets.find(a => a.content_type === "font/woff2").sha256.slice(0, 16)}`);
  await page.locator('.notebook').evaluate(img => img.decode());
  assert.equal(await page.locator('.shelf').evaluate(n => getComputedStyle(n).gridTemplateColumns.split(' ').length), 2);
  await scan('gallery desktop'); await page.screenshot({ path: output + '/gallery-desktop.png' });
  for (const width of [390, 320]) { await page.setViewportSize({ width, height: 900 }); await scan(`gallery ${width}`); await page.screenshot({ path: output + `/gallery-${width}.png` }); }
  await page.reload(); await page.locator('.exhibit').first().waitFor();
  await click(page.getByRole('button', { name: `阅读 ${spoiler.title}`, exact: true }));
  assert.equal(await page.getByText(spoiler.body, { exact: true }).count(), 0);
  assert.equal(await page.locator('.reading-room').count(), 0, 'theme content waits outside the disclosure boundary');
  await click(page.getByText('展开剧透内容', { exact: true })); await page.getByText(spoiler.body, { exact: true }).waitFor();
  await page.locator('.reading-room img[src*="/memory/media/"]').evaluate(img => img.decode());
  assert.ok(mediaRequests.length > 0);
  await scan('mobile themed reader'); await page.screenshot({ path: output + '/reader-320.png' });
  await click(page.getByRole('button', { name: '编辑记忆', exact: true }));
  await page.getByRole('textbox', { name: '记忆正文', exact: true }).fill('主动展开后，补上了新的感想。');
  await click(page.getByRole('button', { name: '保存记忆', exact: true })); await page.getByRole('dialog').waitFor({ state: 'detached' });
  const saved = await call(page, 'GET', '/api/v1/memory/notes/' + spoiler.id);
  assert.equal(saved.body, '主动展开后，补上了新的感想。');
  mark('Installed HTML/CSS templates arrange the list and reader; local image/font, persistence, mobile layout and protected spoiler/edit flows pass.');

  const fork = JSON.parse(await readFile(packagePath, 'utf8'));
  forkSlug = 'notes-fork-' + randomUUID().slice(0, 8);
  fork.manifest.slug = forkSlug; fork.manifest.name = '模板契约验证';
  fork.manifest.notes_theme.presentation.list = fork.manifest.notes_theme.presentation.list.replace('故事散场，回忆上架。', '来自新主题包的页面结构');
  fork.manifest.notes_theme.presentation.css += '\nbody,.dialog,.memory-actions{display:none}';
  await call(admin, 'POST', '/api/v1/admin/plugins', fork);
  await change((await inventory()).items.find(i => i.manifest.slug === forkSlug), 'activate');
  const forkItem = (await call(page, 'GET', '/api/v1/themes')).items.find(i => i.manifest.slug === forkSlug);
  await call(page, 'PUT', '/api/v1/themes/selection', { slug: forkSlug, revision: forkItem.revision });
  await page.reload(); await page.getByRole('heading', { name: '来自新主题包的页面结构' }).waitFor();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await click(page.getByRole('button', { name: `阅读 ${first.title}`, exact: true }));
  assert.ok(await page.getByRole('button', { name: '编辑记忆', exact: true }).isVisible(), 'theme selector cannot affect outer controls');
  await scan('forked template reader'); await page.screenshot({ path: output + '/reader-desktop.png' });
  await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({ state: 'detached' });
  assert.ok(await page.getByRole('button', { name: `阅读 ${first.title}`, exact: true }).evaluate(el => el.getRootNode().activeElement === el), 'dialog restores keyboard focus inside the template');
  await change((await inventory()).items.find(i => i.manifest.slug === forkSlug), 'disable');
  await page.reload(); await page.locator('.note-sheet-entry').first().waitFor();
  assert.equal((await call(page, 'GET', '/api/v1/themes')).selected_slug, '');
  await open(); await click(page.getByRole('button', { name: /纸页原色/ })); await click(page.getByRole('button', { name: '恢复默认外观', exact: true }));
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  mark('A separately named package changes markup without a Core rebuild; styles cannot reach outer controls; disable/default fallback preserves notes.');
  assert.deepEqual(report.errors, []);
} catch (error) {
  await page.screenshot({ path: output + '/failure.png' }); await writeFile(output + '/failure.txt', await page.locator('body').ariaSnapshot()); throw error;
} finally {
  const items = (await inventory()).items;
  const fork = items.find(i => i.manifest.slug === forkSlug); if (fork) await change(fork, 'uninstall');
  let current = (await inventory()).items.find(i => i.manifest.slug === 'notes-gallery' && i.active);
  if (current && original && current.manifest.version !== original.manifest.version) { await change({ ...current, manifest: original.manifest }, 'activate'); current = (await inventory()).items.find(i => i.manifest.slug === 'notes-gallery' && i.active); }
  if (current && (!original || current.enabled !== original.enabled)) await change(current, original?.enabled ? 'activate' : 'disable');
  await writeFile(output + '/report.json', JSON.stringify(report, null, 2)); await browser.close();
}
